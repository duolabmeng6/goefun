// Package ecore 提供文件读写相关功能
//
// 本文件定义了文件读写相关的接口说明，具体实现请参见文件操作.go
//
// 相关函数：
//   - 打开文件: 打开指定文件以便读写操作
//   - 打开内存文件: 在内存中创建虚拟文件
//   - 关闭文件: 关闭已打开的文件
//   - 关闭所有文件: 关闭所有已打开的文件
//   - 锁住文件: 对文件进行锁定操作
//   - 解锁文件: 解除文件锁定
//   - 移动读写位置: 移动文件读写指针位置
//   - 移到文件首: 将读写位置移动到文件开头
//   - 移到文件尾: 将读写位置移动到文件末尾
//   - 读入字节集: 从文件读取字节数据
//   - 写出字节集: 将字节数据写入文件
//   - 读入文本: 从文件读取文本内容
//   - 写出文本: 将文本内容写入文件
//   - 读入一行: 从文件读取一行文本
//   - 写文本行: 向文件写入一行文本
//   - 读入数据: 从文件读取数据
//   - 写出数据: 将数据写入文件
//   - 是否在文件尾: 判断读写位置是否在文件末尾
//   - 取读写位置: 获取当前文件读写位置
//   - 取文件长度: 获取文件大小
//   - 插入字节集: 在指定位置插入字节数据
//   - 插入文本: 在指定位置插入文本
//   - 插入文本行: 在指定位置插入一行文本
//   - 删除数据: 删除指定位置的数据
//   - 打开加密文件: 打开加密的文件
